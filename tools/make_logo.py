"""Draw the site's logo: the vertex K (header, browser tab) and the bilingual seal (footer, about card).

The K is a collider event: its stem is the beam line and its two arms are jets, maroon and gold, leaving one
interaction point. Run `python tools/make_logo.py` after changing it; it writes templates/_logo.html (theme
colours, for the pages) and static/img/favicon.svg (fixed colours, for the browser tab).
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXED = {"ink": "#15171c", "maroon": "#8a1538", "gold": "#a87b2f", "paper": "#f6f3ec"}
THEME = {"ink": "var(--logo-ink)", "maroon": "var(--logo-maroon)", "gold": "var(--logo-gold)", "paper": "var(--logo-paper)"}


def paint(prop, color, prop2=None, color2=None):
    """Colour attributes: theme colours go in one style attribute (they are CSS variables), fixed ones as attributes."""
    pairs = [(prop, color)] + ([(prop2, color2)] if prop2 else [])
    styles = ";".join(f"{p}:{c}" for p, c in pairs if c.startswith("var("))
    attrs = " ".join(f'{p}="{c}"' for p, c in pairs if not c.startswith("var("))
    return " ".join(x for x in (f'style="{styles}"' if styles else "", attrs) if x)


def pt(cx, cy, r, deg):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy + r * math.sin(a)


def wedge(c, cx, cy, r, deg, half, color, op):
    x1, y1 = pt(cx, cy, r, deg - half)
    x2, y2 = pt(cx, cy, r, deg + half)
    return f'<path d="M{cx} {cy}L{x1:.2f} {y1:.2f}A{r} {r} 0 0 1 {x2:.2f} {y2:.2f}Z" {paint("fill", c[color])} fill-opacity="{op}"/>'


def jet(c, cx, cy, r, deg, half, color):
    """A translucent cone, four tracks and a solid core: a jet when large, an arm of the K when small."""
    out = [wedge(c, cx, cy, r, deg, half, color, .22)]
    for d in (deg - half * .6, deg - half * .2, deg + half * .25, deg + half * .65):
        x, y = pt(cx, cy, r * .97, d)
        out.append(f'<line x1="{cx}" y1="{cy}" x2="{x:.2f}" y2="{y:.2f}" {paint("stroke", c[color])} stroke-width=".6" stroke-linecap="round" stroke-opacity=".75"/>')
    out.append(wedge(c, cx, cy, r, deg, half * .38, color, 1))
    return "".join(out)


def mark(c, ring=True):
    vx, vy = 25, 33   # the interaction point, on the stem
    s = []
    if ring:
        s.append(f'<circle cx="32" cy="32" r="30.5" fill="none" {paint("stroke", c["maroon"])} stroke-width="1" stroke-opacity=".55"/>')
        s.append(f'<circle cx="32" cy="32" r="28.2" fill="none" {paint("stroke", c["ink"])} stroke-width=".5" stroke-opacity=".25" stroke-dasharray="1.2 2.2"/>')
    s.append(f'<rect x="20.8" y="15" width="4.2" height="35" {paint("fill", c["ink"])}/>')
    s.append(f'<rect x="17.4" y="14.3" width="11" height="1.4" rx=".4" {paint("fill", c["ink"])}/>')
    s.append(f'<rect x="17.4" y="49.3" width="11" height="1.4" rx=".4" {paint("fill", c["ink"])}/>')
    s.append(jet(c, vx, vy, 27.5, -49, 11, "maroon"))
    s.append(jet(c, vx, vy, 26.5, 45, 11, "gold"))
    for x, y, col, r in ((37.5, 31.5, "gold", .9), (42, 35.5, "maroon", .7), (34, 39.2, "maroon", .6), (31.2, 24.8, "gold", .6), (45.5, 29.5, "gold", .55)):
        s.append(f'<circle cx="{x}" cy="{y}" r="{r}" {paint("fill", c[col])} fill-opacity=".8"/>')
    s.append(f'<circle cx="{vx}" cy="{vy}" r="1.6" {paint("fill", c["paper"], "stroke", c["ink"])} stroke-width=".8"/>')
    return "".join(s)


def seal(c, uid):
    return "".join([
        f'<circle cx="32" cy="32" r="31" fill="none" {paint("stroke", c["maroon"])} stroke-width=".9"/>',
        f'<circle cx="32" cy="32" r="29.6" fill="none" {paint("stroke", c["maroon"])} stroke-width=".35" stroke-opacity=".7"/>',
        f'<circle cx="32" cy="32" r="21.2" fill="none" {paint("stroke", c["ink"])} stroke-width=".45" stroke-opacity=".5"/>',
        f'<defs><path id="{uid}-t" d="M7.6 32A24.4 24.4 0 0 1 56.4 32"/><path id="{uid}-b" d="M5.4 32A26.6 26.6 0 0 0 58.6 32"/></defs>',
        f'<text font-family="Fraunces, Georgia, serif" font-size="4.6" letter-spacing=".9" direction="ltr" {paint("fill", c["ink"])}>'
        f'<textPath href="#{uid}-t" startOffset="50%" text-anchor="middle">KAMEL KHELIFA-KERFA</textPath></text>',
        f'<text font-family="Amiri, serif" font-size="5.6" direction="rtl" {paint("fill", c["ink"])}>'
        f'<textPath href="#{uid}-b" startOffset="50%" text-anchor="middle">كمال خليفة كرفة</textPath></text>',
        f'<circle cx="5.6" cy="32" r=".9" {paint("fill", c["gold"])}/><circle cx="58.4" cy="32" r=".9" {paint("fill", c["gold"])}/>',
        f'<g transform="translate(32 32) scale(.6) translate(-32 -32)">{mark(c, ring=False)}</g>',
    ])


macros = f'''{{# Generated by tools/make_logo.py: edit that script, not this file. #}}
{{% macro mark(cls="brand-mark") -%}}
<svg class="logo {{{{ cls }}}}" viewBox="0 0 64 64" aria-hidden="true" focusable="false">{mark(THEME)}</svg>
{{%- endmacro %}}

{{% macro seal(cls="brand-seal", uid="seal") -%}}
<svg class="logo {{{{ cls }}}}" viewBox="0 0 64 64" aria-hidden="true" focusable="false">{seal(THEME, "{{ uid }}")}</svg>
{{%- endmacro %}}
'''
(ROOT / "templates/_logo.html").write_text(macros, encoding="utf-8")
(ROOT / "static/img/favicon.svg").write_text(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><circle cx="32" cy="32" r="31.5" fill="{FIXED["paper"]}"/>{mark(FIXED)}</svg>\n',
    encoding="utf-8")
print("wrote templates/_logo.html and static/img/favicon.svg")
